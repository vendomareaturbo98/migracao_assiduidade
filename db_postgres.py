"""Conexão PostgreSQL compartilhada pelo sistema administrativo e pelo formulário."""
from __future__ import annotations

import os
import re
from typing import Any

import pandas as pd
import psycopg2
from psycopg2.extras import RealDictCursor


def obter_database_url() -> str:
    """Obtém DATABASE_URL do ambiente ou dos Secrets do Streamlit."""
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        try:
            import streamlit as st
            url = str(st.secrets.get("DATABASE_URL", "")).strip()
        except Exception:
            url = ""
    if not url:
        raise RuntimeError(
            "DATABASE_URL não foi configurada. Configure-a nos Secrets do "
            "Streamlit ou na variável de ambiente DATABASE_URL."
        )
    if url.startswith("postgres://"):
        url = "postgresql://" + url[len("postgres://"):]
    if not url.startswith("postgresql://"):
        raise RuntimeError(
            "DATABASE_URL deve começar com postgresql:// ou postgres://."
        )
    return url


def _sql_pg(sql: str) -> str:
    # O código original usa '?' como placeholder (SQLite). No psycopg2 é '%s'.
    return re.sub(r"\?", "%s", sql)


class CursorPG:
    def __init__(self, cursor, retorna_id: bool = False):
        self._cursor = cursor
        self._retorna_id = retorna_id
        self._id_cache = None
        self._id_lido = False

    @property
    def lastrowid(self):
        if not self._retorna_id:
            return None
        if not self._id_lido:
            row = self._cursor.fetchone()
            self._id_cache = row["id"] if row else None
            self._id_lido = True
        return self._id_cache

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()


class ConexaoPG:
    """Adaptador pequeno para manter compatibilidade com conn.execute do SQLite."""
    def __init__(self):
        self.raw = psycopg2.connect(obter_database_url(), sslmode="require")

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc, tb):
        try:
            if exc_type is None:
                self.raw.commit()
            else:
                self.raw.rollback()
        finally:
            self.raw.close()
        return False

    def execute(self, sql: str, parametros=()):
        statement = sql.strip()
        retorna_id = False
        if re.match(r"INSERT\s+INTO\s+treinamentos\b", statement, re.I) and not re.search(
            r"\bRETURNING\b", statement, re.I
        ):
            statement += " RETURNING id"
            retorna_id = True
        cursor = self.raw.cursor(cursor_factory=RealDictCursor)
        cursor.execute(_sql_pg(statement), parametros or ())
        return CursorPG(cursor, retorna_id=retorna_id)

    def executemany(self, sql: str, sequencia):
        cursor = self.raw.cursor(cursor_factory=RealDictCursor)
        cursor.executemany(_sql_pg(sql), sequencia)
        return CursorPG(cursor)


def conectar() -> ConexaoPG:
    return ConexaoPG()


def inicializar_banco() -> None:
    """Cria as tabelas se ainda não existirem; não apaga dados existentes."""
    comandos = [
        """CREATE TABLE IF NOT EXISTS colaboradores (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            nome TEXT NOT NULL,
            nome_chave TEXT NOT NULL UNIQUE,
            matricula TEXT,
            cargo TEXT NOT NULL DEFAULT '',
            ativo INTEGER NOT NULL DEFAULT 1,
            criado_em TEXT DEFAULT (CURRENT_TIMESTAMP::text)
        )""",
        """CREATE TABLE IF NOT EXISTS treinamentos (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            titulo TEXT NOT NULL,
            data TEXT NOT NULL,
            hora_inicio TEXT NOT NULL,
            hora_fim TEXT NOT NULL,
            carga_horaria DOUBLE PRECISION NOT NULL,
            publico TEXT NOT NULL,
            situacao TEXT NOT NULL DEFAULT 'Agendado',
            observacoes TEXT DEFAULT '',
            criado_em TEXT DEFAULT (CURRENT_TIMESTAMP::text)
        )""",
        """CREATE TABLE IF NOT EXISTS elegibilidade (
            treinamento_id BIGINT NOT NULL,
            colaborador_id BIGINT NOT NULL,
            PRIMARY KEY (treinamento_id, colaborador_id),
            FOREIGN KEY (treinamento_id) REFERENCES treinamentos(id) ON DELETE CASCADE,
            FOREIGN KEY (colaborador_id) REFERENCES colaboradores(id)
        )""",
        """CREATE TABLE IF NOT EXISTS presencas (
            treinamento_id BIGINT NOT NULL,
            colaborador_id BIGINT NOT NULL,
            presente INTEGER NOT NULL DEFAULT 0,
            observacao TEXT DEFAULT '',
            atualizado_em TEXT DEFAULT (CURRENT_TIMESTAMP::text),
            PRIMARY KEY (treinamento_id, colaborador_id),
            FOREIGN KEY (treinamento_id) REFERENCES treinamentos(id) ON DELETE CASCADE,
            FOREIGN KEY (colaborador_id) REFERENCES colaboradores(id)
        )""",
        "CREATE INDEX IF NOT EXISTS idx_colaboradores_matricula ON colaboradores(matricula)",
        "CREATE INDEX IF NOT EXISTS idx_treinamentos_data ON treinamentos(data)",
    ]
    with conectar() as conn:
        for comando in comandos:
            conn.execute(comando)


def consultar(sql: str, parametros=()) -> pd.DataFrame:
    # pandas usa a conexão psycopg2 e placeholders %s.
    with conectar() as conn:
        return pd.read_sql_query(_sql_pg(sql), conn.raw, params=parametros or None)


def executar(sql: str, parametros=()) -> None:
    with conectar() as conn:
        conn.execute(sql, parametros)
